const tables = { en, zh } as const;
export type Language = keyof typeof tables;

export const lang = $state({ current: "en" as Language });

/** The text of `key` in the current language, with `{name}` replaced by `values.name`. */
export function t(key: Key, values: Record<string, string | number> = {}): string {
  const text: string = tables[lang.current][key];
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}
